import { z } from "zod";
import { CITIES } from "./constants";
import { LISTING_LIMITS, REPORT_NOTE_MAX, REPORT_REASONS } from "./lister";
import { FURNISHINGS, ROOM_TAGS, ROOM_TYPES, SWIPE_ACTIONS } from "./listing";
import { MESSAGE_MAX_LENGTH } from "./match";
import {
  ABOUT_MAX_LENGTH,
  AGE_RANGES,
  LIFESTYLE,
  LIFESTYLE_KEYS,
  MODES,
  MOVE_IN,
  NAME_MAX_LENGTH,
  OCCUPATIONS,
  STAY,
} from "./tenant";

/*
 * The contract between the API and the app, as Zod schemas. The types the app
 * uses are inferred from these (see listing.ts), so the two cannot drift.
 *
 * Import this file only where data is actually validated: the server, and
 * tests. It is kept out of the main entry point so the validation library is
 * not shipped to phones, which only need the types.
 */

export const CitySchema = z.enum(CITIES);
export const RoomTypeSchema = z.enum(ROOM_TYPES);
export const FurnishingSchema = z.enum(FURNISHINGS);
export const SwipeActionSchema = z.enum(SWIPE_ACTIONS);

export const ListingPhotoSchema = z.object({
  url: z.url(),
  roomTag: z.enum(ROOM_TAGS),
  /** The photo's main colour as a hex string; drives the ambient glow behind the deck. */
  dominantColor: z.string().regex(/^#[0-9a-f]{6}$/i),
});

/** A rule the household has, phrased as something that is or is not okay. */
export const HouseRuleSchema = z.object({
  label: z.string(),
  allowed: z.boolean(),
});

export const CompatibilitySchema = z.object({
  /** Fit only (budget, location, timing, lifestyle). Never includes ranking extras. */
  percent: z.number().int().min(0).max(100),
  reasons: z.array(z.string()).max(3),
  caution: z.string().optional(),
});

/**
 * Roughly where a flat is: a point near it, never the address. The server
 * shifts the real location before sending it (docs/SPEC.md section 10.1).
 */
export const AreaSchema = z.object({
  lat: z.number().min(-90).max(90),
  lng: z.number().min(-180).max(180),
});

export const ListerSummarySchema = z.object({
  name: z.string(),
  role: z.enum(["owner", "flatmate"]),
  about: z.string(),
  flatmateCount: z.number().int().min(0),
});

export const ListingSchema = z.object({
  id: z.string(),
  title: z.string(),
  description: z.string(),
  city: CitySchema,
  locality: z.string(),
  /** Rounded to 5 minutes by the server; null when the tenant has set no commute anchor. */
  commuteMinutes: z.number().int().nullable(),
  /** The approximate area, for the neighbourhood map. */
  area: AreaSchema,
  /** Handy things close by, e.g. "Metro 600 m". */
  nearby: z.array(z.string()),

  // Money is whole rupees.
  rent: z.number().int(),
  maintenance: z.number().int(),
  utilitiesEstimate: z.number().int(),
  deposit: z.number().int(),

  roomType: RoomTypeSchema,
  bhk: z.number().int().min(1),
  furnishing: FurnishingSchema,
  /** ISO date, e.g. "2026-12-01". */
  availableFrom: z.iso.date(),

  photos: z.array(ListingPhotoSchema).min(1),
  amenities: z.array(z.string()),
  houseRules: z.array(HouseRuleSchema),
  societyRules: z.array(z.string()),
  expectations: z.array(z.string()),

  lister: ListerSummarySchema,
  compatibility: CompatibilitySchema,

  isOpen: z.boolean(),
  isVerified: z.boolean(),
  /** Seed data shown with a "Demo" tag. */
  isSeed: z.boolean(),
  /** Set when the listing is a stretch pick, e.g. "₹1,500 over budget". */
  stretchLabel: z.string().optional(),
});

export const FeedPageSchema = z.object({
  items: z.array(ListingSchema),
  /** Pass back to get the next page; null when there are no more. */
  nextCursor: z.string().nullable(),
});

/** What the tenant has narrowed the deck to. Empty lists and null mean "anything". */
export const FeedFiltersSchema = z.object({
  /** The city being searched. Always set; it is not counted as a filter the person chose. */
  city: CitySchema,
  /** The most the flat may cost each month, all in (rent + maintenance + utilities). */
  budgetMax: z.number().int().positive().nullable(),
  localities: z.array(z.string()),
  roomTypes: z.array(RoomTypeSchema),
});

export const SwipeSchema = z.object({
  /** Generated by the client, so a retried request is recognised and ignored. */
  clientId: z.uuid(),
  listingId: z.string(),
  action: SwipeActionSchema,
});

/** One chat message. "me" and "them" are from the point of view of whoever asked. */
export const MessageSchema = z.object({
  id: z.string(),
  matchId: z.string(),
  from: z.enum(["me", "them"]),
  body: z.string().min(1).max(MESSAGE_MAX_LENGTH),
  sentAt: z.iso.datetime(),
});

/** The part of a listing that stays private until both sides have matched. */
export const AddressSchema = z.object({
  society: z.string(),
  line: z.string(),
});

// A match without the applicant, which is defined further down. See MatchSchema.
const MatchCoreSchema = z.object({
  id: z.string(),
  /** Whether the person asking is the tenant or the lister in this match. */
  side: z.enum(["tenant", "lister"]),
  /** The other person: the lister for a tenant, the tenant for a lister. */
  person: z.object({ name: z.string(), about: z.string() }),
  listing: ListingSchema,
  address: AddressSchema,
  matchedAt: z.iso.datetime(),
  lastMessage: MessageSchema.nullable(),
  /** Messages from the other person that have not been read yet. */
  unreadCount: z.number().int().min(0),
});

/** A like the lister has not answered yet. */
export const PendingLikeSchema = z.object({
  listing: ListingSchema,
  likedAt: z.iso.datetime(),
});

/** One answer per lifestyle question the tenant has answered. */
export const LifestyleSchema = z.object({
  food: z.enum(LIFESTYLE.food).optional(),
  smoking: z.enum(LIFESTYLE.smoking).optional(),
  drinking: z.enum(LIFESTYLE.drinking).optional(),
  pets: z.enum(LIFESTYLE.pets).optional(),
  sleep: z.enum(LIFESTYLE.sleep).optional(),
  cleanliness: z.enum(LIFESTYLE.cleanliness).optional(),
  guests: z.enum(LIFESTYLE.guests).optional(),
  workMode: z.enum(LIFESTYLE.workMode).optional(),
});

/** What a tenant is looking for. These become the deck's default filters. */
export const TenantPreferencesSchema = z.object({
  city: CitySchema,
  /** The most they will pay each month, all in. Null means no limit. */
  budgetMax: z.number().int().positive().nullable(),
  localities: z.array(z.string()),
  moveIn: z.enum(MOVE_IN).nullable(),
  stay: z.enum(STAY).nullable(),
  roomTypes: z.array(RoomTypeSchema),
  lifestyle: LifestyleSchema,
  /** Lifestyle questions where a mismatch rules a flat out. */
  dealbreakers: z.array(z.enum(LIFESTYLE_KEYS)),
});

/** The tenant: a little about them, and what they are looking for. */
export const TenantProfileSchema = z.object({
  name: z.string().max(NAME_MAX_LENGTH),
  ageRange: z.enum(AGE_RANGES).nullable(),
  occupation: z.enum(OCCUPATIONS).nullable(),
  about: z.string().max(ABOUT_MAX_LENGTH),
  preferences: TenantPreferencesSchema,
  /** Which side of the app they are using: looking for a flat, or listing one. */
  mode: z.enum(MODES),
  /** When they finished (or skipped) onboarding. Null until then. */
  onboardedAt: z.iso.datetime().nullable(),
});

/** A tenant who has liked the lister's flat and is waiting for an answer. */
export const ApplicantSchema = z.object({
  id: z.string(),
  listingId: z.string(),
  name: z.string(),
  ageRange: z.enum(AGE_RANGES),
  occupation: z.enum(OCCUPATIONS),
  about: z.string(),
  lifestyle: LifestyleSchema,
  /** How well they fit this household, with the reasons. */
  compatibility: CompatibilitySchema,
  /** A short note, if they sent the like with one. */
  note: z.string().optional(),
  likedAt: z.iso.datetime(),
});

/** A like the lister accepted: chat is open and, for the tenant, the address is unlocked. */
export const MatchSchema = MatchCoreSchema.extend({
  /** For a lister: the tenant they matched with. Null on the tenant's side. */
  applicant: ApplicantSchema.nullable(),
});

/** Everything a lister fills in to post a flat. The society and address line stay private. */
export const ListingDraftSchema = z.object({
  title: z.string().trim().min(LISTING_LIMITS.titleMin).max(LISTING_LIMITS.titleMax),
  description: z.string().max(LISTING_LIMITS.descriptionMax),
  city: CitySchema,
  locality: z.string().min(1).max(80),
  society: z.string().trim().min(1).max(LISTING_LIMITS.societyMax),
  addressLine: z.string().trim().min(1).max(LISTING_LIMITS.addressLineMax),
  roomType: RoomTypeSchema,
  bhk: z.number().int().min(1).max(6),
  furnishing: FurnishingSchema,
  availableFrom: z.iso.date(),
  rent: z.number().int().min(LISTING_LIMITS.rentMin).max(LISTING_LIMITS.rentMax),
  maintenance: z.number().int().min(0),
  utilitiesEstimate: z.number().int().min(0),
  depositMonths: z.number().int().min(0).max(LISTING_LIMITS.depositMonthsMax),
  photos: z.array(ListingPhotoSchema).min(LISTING_LIMITS.photosMin).max(LISTING_LIMITS.photosMax),
  amenities: z.array(z.string()),
  houseRules: z.array(HouseRuleSchema),
  societyRules: z.array(z.string()),
  expectations: z.array(z.string()),
});

/** A flat the person has posted, with its status and how it is doing. */
export const MyListingSchema = ListingDraftSchema.extend({
  id: z.string(),
  /** True once the lister has confirmed, by their device's location, that they posted from the flat. */
  isVerified: z.boolean(),
  /** When the flat comes off the board unless the lister says it is still available. Null: never. */
  expiresAt: z.iso.datetime().nullable(),
  /** True when enough people reported the flat that it was taken off the board. */
  underReview: z.boolean(),
  /** The VACANCY sign: true while the flat is open to likes. */
  isOpen: z.boolean(),
  createdAt: z.iso.datetime(),
  /** Tenants waiting for an answer. */
  interestedCount: z.number().int().min(0),
  matchCount: z.number().int().min(0),
});

/** How the person is signed in. A guest has no email and lives in one browser. */
export const AccountSchema = z.object({
  isGuest: z.boolean(),
  email: z.email().nullable(),
  /** Whether this server offers Google sign-in at all. */
  canSignIn: z.boolean(),
  /** Whether this person may upload their own photos (needs image storage, and an account). */
  canUpload: z.boolean(),
});

/** Where a device says it is, from the browser. `accuracy` is the radius of doubt, in metres. */
export const DevicePositionSchema = z.object({
  lat: z.number().min(-90).max(90),
  lng: z.number().min(-180).max(180),
  accuracy: z.number().min(0).max(100_000),
});

/** A flat as it is sent for posting: the form's answers, and where the lister is standing if they chose to say. */
export const ListingSubmissionSchema = ListingDraftSchema.extend({
  postedFrom: DevicePositionSchema.optional(),
});

/** What the app needs to send one photo straight to the image store. Good for that one photo only. */
export const UploadTicketSchema = z.object({
  uploadUrl: z.url(),
  /** Sent as form fields along with the file, exactly as given. */
  fields: z.record(z.string(), z.string()),
});

/** A report about a flat, from someone who thinks something is wrong with it. */
export const ReportSchema = z.object({
  reason: z.enum(REPORT_REASONS),
  note: z.string().trim().max(REPORT_NOTE_MAX).optional(),
});
